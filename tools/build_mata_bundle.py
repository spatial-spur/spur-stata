"""Generate the installed Mata source bundle; run from any working directory."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
files = sorted((ROOT / "mata").glob("*.mata"))
sources = {p: p.read_text() for p in files}
functions = set()
structs = set()
for source in sources.values():
    functions.update(re.findall(r"^(?:real|string|void|struct\s+\w+)\s+(?:(?:matrix|scalar|vector|rowvector|colvector)\s+)?(\w+)\s*\(", source, re.M))
    structs.update(re.findall(r"^struct\s+(\w+)\s*\{", source, re.M))
rename = {name: "sv2_" + name for name in functions}
rename.update({name: "sv2_s_" + name.removeprefix("struct_") for name in structs})
rename["latlongflag"] = "sv2_latlongflag"
pattern = re.compile(r"\b(" + "|".join(sorted(map(re.escape, rename), key=len, reverse=True)) + r")\b")
def replace(source):
    return pattern.sub(lambda match: rename[match[0]], source)

# Helpers before callers; Mata also permits forward references within a file.
ordered = []
pending = set(files)
while pending:
    ready = []
    for path in sorted(pending):
        dependencies = {other for other in pending if other != path and any(re.search(r"\b" + re.escape(fn) + r"\s*\(", sources[path]) for fn in functions if re.search(r"^(?:real|string|void|struct\s+\w+)\s+(?:(?:matrix|scalar|vector|rowvector|colvector)\s+)?" + re.escape(fn) + r"\s*\(", sources[other], re.M))}
        if not dependencies:
            ready.append(path)
    if not ready:
        raise RuntimeError("Cycle in Mata source dependencies")
    ordered.extend(ready)
    pending.difference_update(ready)

bundle = "* Generated by tools/build_mata_bundle.py; edit mata/*.mata instead.\n"
for path in ordered:
    bundle += "\n* Source: mata/" + path.name + "\n" + replace(sources[path]) + "\n"
bundle += "\nmata:\nreal scalar sv2_version() { return(20261110) }\nend\n"
(ROOT / "spur_mata_source.do").write_text("\n".join(line.rstrip() for line in bundle.splitlines()) + "\n")
for path in ROOT.glob("*.ado"):
    if path.name == "spur_mata.ado":
        continue
    source = path.read_text()
    for original in functions:
        source = re.sub(r"\b" + re.escape(original) + r"(?=\s*\()", rename[original], source)
    if "\tversion 14" in source and "\tspur_mata\n" not in source:
        source = source.replace("\tversion 14", "\tversion 14\n\tspur_mata", 1)
    elif "    version 14" in source and "    spur_mata\n" not in source:
        source = source.replace("    version 14", "    version 14\n    spur_mata", 1)
    path.write_text("\n".join(line.rstrip() for line in source.splitlines()) + "\n")
